def rows(text):
    out = {}
    for m in re.finditer(r"^\| (\d+\.\d+) \| (.+?) \|", text, re.M):
        t = re.sub(r"<break[^>]*>|`\[CONFIRM[^`]*`|\*\*", "", m.group(2)).strip()
        out.setdefault(m.group(1), re.sub(r"\s+", " ", t))
    return out


